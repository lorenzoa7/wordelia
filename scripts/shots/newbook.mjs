// Create a book from the library and type the first lines.
export default async function ({ page, shot }) {
  await page.locator('.library-actions .btn-ribbon').click()
  await page.waitForTimeout(500)
  await page.locator('.dialog input').first().fill('Um Livro Novo')
  await page.locator('.dialog input').nth(1).fill('Autora Teste')
  await page.locator('.dialog-foot .btn-primary').click()
  await page.waitForSelector('.manuscript', { timeout: 15000 })
  await page.waitForTimeout(700)
  await shot('empty-chapter')
  await page.locator('.manuscript').click()
  await page.keyboard.type('Era uma vez um farol... ')
  await page.keyboard.press('Enter')
  await page.keyboard.type('- Um hífen no começo fica texto.')
  await page.keyboard.press('Enter')
  await page.keyboard.type('-- Quem esta ai? -- perguntou "ela".')
  await page.keyboard.press('Enter')
  await page.keyboard.type('* * * ')
  await page.keyboard.type('Nova cena.')
  await page.waitForTimeout(900)
  const text = await page.locator('.manuscript').innerText()
  console.log(JSON.stringify(text))
  await shot('typed')
  if (!text.includes('— Quem esta ai? — perguntou “ela”.')) throw new Error('Smart typing failed')
  if (!text.includes('farol…')) throw new Error('Ellipsis failed')
  if (!(await page.locator('.manuscript .scene-break').count())) throw new Error('Scene break failed')
  if (await page.locator('.manuscript ul').count()) throw new Error('A list appeared')
}
