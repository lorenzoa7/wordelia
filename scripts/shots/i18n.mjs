// Screens in another interface language, to check translations and layout.
// Usage: I18N_LANG=pt-BR node scripts/shot.mjs i18n   (or es)
export default async function ({ page, shot, openBook }) {
  const lang = process.env.I18N_LANG || 'pt-BR'
  await page.evaluate((l) => window.__wordelia.app.getState().updateSettings({ language: l }), lang)
  await page.waitForTimeout(500)
  await shot(`${lang}-library`)
  await openBook()
  await page.waitForTimeout(500)
  // Selection menu
  const p = page.locator('.manuscript p').first()
  await p.click()
  await page.keyboard.press('Home')
  await page.keyboard.down('Shift')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.up('Shift')
  await page.waitForTimeout(400)
  await shot(`${lang}-write-selection`)
  await page.keyboard.press('Control+j')
  await page.waitForSelector('.review-accept', { timeout: 15000 })
  await page.waitForTimeout(400)
  await shot(`${lang}-review`)
  await page.keyboard.press('Escape')
  await page.locator('.composer-input').fill('Can you improve the opening paragraph?')
  await page.keyboard.press('Enter')
  await page.waitForSelector('.proposal', { timeout: 15000 })
  await page.waitForTimeout(1200)
  await shot(`${lang}-chat`)
  await page.keyboard.press('Control+2')
  await page.waitForTimeout(700)
  await shot(`${lang}-plan`)
  await page.keyboard.press('Control+,')
  await page.waitForTimeout(600)
  await shot(`${lang}-settings-general`)
  for (const tab of [1, 2, 3]) {
    await page.locator('.settings-tab').nth(tab).click()
    await page.waitForTimeout(500)
    await shot(`${lang}-settings-${tab}`)
  }
  await page.keyboard.press('Escape')
  await page.waitForTimeout(300)
  await page.keyboard.press('Control+Shift+E')
  await page.waitForTimeout(700)
  await shot(`${lang}-export`)
}
